CREATE TABLE accounts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    pic TEXT,
    last_login_at TIMESTAMP,
    gender TEXT NOT NULL,
    accepted_tos BOOLEAN NOT NULL DEFAULT FALSE,
    banned BOOLEAN NOT NULL DEFAULT FALSE,
    admin BOOLEAN NOT NULL DEFAULT FALSE,
    quit_status TEXT CHECK (quit_status IN ('not_ready', 'ready_to_quit', 'already_quit')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE settings_wallpaper (
    acc_id INTEGER PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    file_name TEXT,
    tile_x BOOLEAN NOT NULL DEFAULT TRUE,
    tile_y BOOLEAN NOT NULL DEFAULT TRUE,
    scale REAL NOT NULL DEFAULT 0.1,
    mode TEXT NOT NULL DEFAULT 'Tiled' CHECK (mode IN ('Auto', 'Stretch', 'Tiled')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    route TEXT NOT NULL,
    brand TEXT,
    description TEXT,
    image_path TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    serving_size NUMERIC NOT NULL CHECK (serving_size > 0),
    serving_unit TEXT NOT NULL CHECK (serving_unit IN ('mg', 'mL', 'unit')),
    serving_description TEXT
);

CREATE TABLE compounds (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    common_name TEXT NOT NULL,
    iupac_name TEXT NOT NULL DEFAULT '',
    half_life_seconds BIGINT CHECK (half_life_seconds > 0),
    image_path TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (common_name)
);

CREATE TABLE product_compounds (
    product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    compound_id INTEGER NOT NULL REFERENCES compounds(id),
    compound_amount BIGINT NOT NULL CHECK (compound_amount > 0),
    compound_units TEXT NOT NULL CHECK (compound_units IN ('g', 'mg', 'ug')),
    PRIMARY KEY (product_id, compound_id)
);

CREATE TABLE compound_metabolites (
    parent_compound_id INTEGER NOT NULL REFERENCES compounds(id) ON DELETE CASCADE,
    metabolite_compound_id INTEGER NOT NULL REFERENCES compounds(id) ON DELETE CASCADE,
    PRIMARY KEY (parent_compound_id, metabolite_compound_id),
    CHECK (parent_compound_id <> metabolite_compound_id)
);

CREATE TABLE entries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acc_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    product_id INTEGER NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (product_id) NOT NULL REFERENCES products(id) ON DELETE RESTRICT
);

CREATE TABLE entry_compounds (
    entry_id INTEGER NOT NULL REFERENCES entries(id) ON DELETE CASCADE,
    compound_id INTEGER NOT NULL REFERENCES compounds(id),
    amount NUMERIC NOT NULL CHECK (amount >= 0),
    units TEXT NOT NULL CHECK (units IN ('mg', 'mL')),
    PRIMARY KEY (entry_id, compound_id)
);
