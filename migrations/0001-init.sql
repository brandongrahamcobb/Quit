CREATE TABLE accounts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    pic TEXT,
    last_login_at TIMESTAMP,
    gender TEXT NOT NULL,
    accepted_tos BOOLEAN NOT NULL DEFAULT FALSE,
    banned BOOLEAN NOT NULL DEFAULT FALSE,
    admin BOOLEAN NOT NULL DEFAULT FALSE,
    quit_status TEXT CHECK (quit_status IN ('not_ready', 'ready_to_quit', 'already_quit')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE settings_wallpaper (
    acc_id INTEGER PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    file_name TEXT,
    tile_x BOOLEAN NOT NULL DEFAULT TRUE,
    tile_y BOOLEAN NOT NULL DEFAULT TRUE,
    scale REAL NOT NULL DEFAULT 0.1,
    mode TEXT NOT NULL DEFAULT 'Tiled' CHECK (mode IN ('Auto', 'Stretch', 'Tiled')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE substances (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acc_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('simple', 'complex')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (acc_id, name)
);

CREATE TABLE compounds (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acc_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    half_life_seconds DOUBLE PRECISION CHECK (half_life_seconds > 0),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (acc_id, name)
);

CREATE TABLE substance_compounds (
    substance_id INTEGER NOT NULL REFERENCES substances(id) ON DELETE CASCADE,
    compound_id INTEGER NOT NULL REFERENCES compounds(id) ON DELETE CASCADE,
    compound_amount BIGINT NOT NULL CHECK (compound_amount > 0),
    compound_units TEXT NOT NULL CHECK (compound_units IN ('g', 'mg', 'ug')),
    substance_amount BIGINT NOT NULL CHECK (substance_amount > 0),
    substance_units TEXT NOT NULL CHECK (substance_units IN ('g', 'mg', 'ug')),
    PRIMARY KEY (substance_id, compound_id)
);

CREATE TABLE compound_metabolites (
    parent_compound_id INTEGER NOT NULL REFERENCES compounds(id) ON DELETE CASCADE,
    metabolite_compound_id INTEGER NOT NULL REFERENCES compounds(id) ON DELETE CASCADE,
    PRIMARY KEY (parent_compound_id, metabolite_compound_id),
    CHECK (parent_compound_id <> metabolite_compound_id)
);

CREATE TABLE routes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acc_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (acc_id, name)
);

CREATE TABLE substance_routes (
    substance_id INTEGER NOT NULL REFERENCES substances(id) ON DELETE CASCADE,
    route_id INTEGER NOT NULL REFERENCES routes(id) ON DELETE CASCADE,
    PRIMARY KEY (substance_id, route_id)
);

CREATE TABLE entries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acc_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    mass INTEGER NOT NULL CHECK (mass > 0),
    units TEXT NOT NULL CHECK (units IN ('g', 'mg', 'ug')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    substance_id INTEGER NOT NULL,
    route_id INTEGER NOT NULL,
    FOREIGN KEY (substance_id, route_id)
        REFERENCES substance_routes (substance_id, route_id)
        ON DELETE RESTRICT
);


